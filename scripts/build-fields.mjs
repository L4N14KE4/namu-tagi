// 분야에 맞으면 { hit: 맞은 분류들, works } 아니면 null, 성범죄 등은 { banned }
function match(f, d) {
  if (!d || d.status !== 200 || d.disambig || skipTitle(d.canonical)) return null;
  const cats = catsOf(d);
  const hit = cats.filter(c => f.inc.test(c) && !f.exc?.test(c));
  if (f.medium && !hit.length) hit.push(...charCats(d).filter(c => lineage(c).some(x => CHARACTER.test(x))));
  if (!hit.length) return null;
  for (const [label, re, unless, on] of f.ban ?? []) { // 제목도 본다(냉전, 제1차 세계 대전)
    const why = (on === 'title' ? [d.canonical] : [d.canonical, ...cats]).filter(c => re.test(c));
    if (why.length && !(unless && cats.some(c => unless.test(c)))) return { banned: label, why };
  }
  if (f.medium) {
    const works = [...new Set([...mediumHits(f.medium, cats), ...charCats(d).filter(c => lineage(c).some(x => MEDIUM[f.medium].test(x)))])];
    const own = cats.filter(c => f.own.test(c));
    if (!works.length && !own.length) return null;
    return { hit, works: [...works, ...own] };
  }
  return { hit };
}
