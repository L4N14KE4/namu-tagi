const TICK = join(tmpdir(), 'namu-request-tick');
const touch = () => closeSync(openSync(TICK, 'w'));
async function polite() {
  for (;;) {
    let last = 0; try { last = statSync(TICK).mtimeMs; } catch {}
    const wait = last + 1000 - Date.now();
    if (wait <= 0) return;
    await sleep(wait);
  }
}
// build-words.mjs의 head(): 응답 앞부분만 읽고 끊는다. 429, 5xx는 쉬었다 다시.
async function head(url, limit) {
  if (args.includes('--report')) throw new Error('--report인데 요청이 필요해요: ' + url);
  for (let attempt = 0; attempt < 4; attempt++) {
    await polite();
    try {
      requests++;
      const res = await fetch(url, { headers: { 'User-Agent': UA }, redirect: 'follow' });
      if (res.status === 429 || res.status >= 500) throw new Error('HTTP ' + res.status);
      const reader = res.body.getReader();
      const chunks = []; let size = 0;
      while (size < limit) { const { done, value } = await reader.read(); if (done) break; chunks.push(value); size += value.length; }
      reader.cancel().catch(() => {});
      touch();
      return { status: res.status, url: res.url, html: Buffer.concat(chunks).toString('utf8') };
    } catch (e) {
      touch();
      console.warn(`  재시도 ${attempt + 1}: ${e.message} ${decodeURIComponent(url)}`);
      await sleep(10000 * (attempt + 1));
    }
  }
  return { status: 0, url, html: '' };
}

const catLinks = html => [...new Set([...html.matchAll(/href="\/w\/(%EB%B6%84%EB%A5%98:[^"#?]+)"/g)].map(m => decodeURIComponent(m[1]).slice(3)))];

// 문서: 정식 이름, 동음이의어, 분류. 분류 줄은 HTML 앞 18KB 안에 있다.
// 자기 이름 분류만 붙었거나 그 밖에 둘 이하인 문서(고양이, 원자, Microsoft Windows)는 자기 이름 분류 페이지의 상위 분류를 물려받는다(inh).
async function doc(title) {
  let d = cache.docs[title];
  if (!d) {
    const r = await head('https://namu.wiki/w/' + enc(title), 40000);
    const canon = r.html.match(/<link rel="canonical" href="https:\/\/namu\.wiki\/w\/([^"]+)"/);
    const cats = catLinks(r.html);
    d = cache.docs[title] = { status: r.status, canonical: canon ? decodeURIComponent(canon[1]) : title, disambig: cats.includes('동음이의어'), cats };
    save();
  }
  const others = d.cats.filter(c => c !== d.canonical).length;
  if (d.status === 200 && !d.inh?.length && others < d.cats.length && others <= 2) {
    d.inh = (await cat(d.canonical, false)).parents ?? [];
    save();
  }
  return d;
}

async function backlinks(canonical) {
  if (!(canonical in cache.bl)) {
    const r = await head('https://namu.wiki/backlink/' + enc(canonical), 60000);
    const m = r.html.match(/문서 \(([\d,]+)\)/);
    cache.bl[canonical] = r.status === 200 && m ? Number(m[1].replace(/,/g, '')) : null;
    save();
  }
  return cache.bl[canonical];
}

// 분류 페이지: 맨 위 상위 분류, "하위 분류" 구역, "... 분류에 속하는 문서" 구역. 구역마다 100개씩 나뉘고 '다음' 링크가 cfrom으로 이어진다.
function parseCat(html, name) {
  const links = (s, e) => [...html.slice(s, e).matchAll(/<a [^>]*href="\/w\/([^"#?]+)"/g)].map(m => decodeURIComponent(m[1]));
  const first = html.indexOf('id="category-');
  const section = id => {
    const i = html.indexOf(`id="category-${id}"`);
    if (i < 0) return [];
    const ends = [html.indexOf('id="category-', i + 10), html.indexOf('이 저작물은', i)].filter(x => x > 0);
    return links(i, Math.min(html.length, ...ends));
  };
  const next = ns => html.match(new RegExp(`href="(/w/[^"]*\\?namespace=${encodeURIComponent(ns)}&amp;cfrom=[^"]*)"`))?.[1].replace(/&amp;/g, '&');
  return {
    parents: first < 0 ? [] : links(0, first).filter(l => l.startsWith('분류:')).map(l => l.slice(3)).filter(p => p !== name),
    subs: section('분류').filter(l => l.startsWith('분류:')).map(l => l.slice(3)),
    docs: section('문서').filter(l => !l.startsWith('분류:')),
    nextDocs: next('문서'), nextSubs: next('분류'),
    total: Number(html.match(/분류에 속하는 문서[\s\S]{0,200}?전체 ([\d,]+)개 문서/)?.[1].replace(/,/g, '') ?? 0),
  };
}

// full이 아니면 첫 페이지만(상위 분류만 필요할 때). 그렇게 읽은 것은 partial로 남겨 나중에 필요하면 다시 읽는다.
async function cat(name, full = true) {
  if (cache.cats[name] && !(full && cache.cats[name].partial && !args.includes('--report'))) return cache.cats[name];
  const r = await head('https://namu.wiki/w/' + enc('분류:' + name), 400000);
  if (r.status !== 200) return (cache.cats[name] = { status: r.status });
  const p = parseCat(r.html, name);
  const c = { status: 200, parents: p.parents, subs: new Set(p.subs), docs: new Set(p.docs), total: p.total, pages: 1 };
  if (!full && (p.nextDocs || p.nextSubs)) c.partial = true;
  for (const kind of full ? ['nextDocs', 'nextSubs'] : []) {
    for (let url = p[kind]; url && c.pages < MAX_CAT_PAGES; c.pages++) {
      const q = parseCat((await head('https://namu.wiki' + url, 400000)).html, name);
      q.subs.forEach(s => c.subs.add(s)); q.docs.forEach(x => c.docs.add(x));
      url = q[kind];
    }
  }
  cache.cats[name] = { ...c, subs: [...c.subs], docs: [...c.docs] };
  save();
  return cache.cats[name];
}

